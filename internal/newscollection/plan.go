// Package newscollection builds bounded, replayable collection units. It never fetches news.
package newscollection

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"strings"
	"time"

	"github.com/kosw006/trader-controller/internal/domain"
)

const Version = "news-v1"
const EnrichmentPolicy = "news-title-relevance-v1"

type Request struct {
	Provider        string   `json:"provider"`
	Queries         []string `json:"queries,omitempty"`
	StartDate       string   `json:"startDate,omitempty"`
	EndDate         string   `json:"endDate,omitempty"`      // inclusive UTC dates
	LookbackDays    int      `json:"lookbackDays,omitempty"` // completed UTC days, for schedules
	AssetIDs        []int64  `json:"assetIds,omitempty"`
	Targets         []Target `json:"-"` // populated only by server catalog resolution
	DurableRecovery bool     `json:"durableRecovery,omitempty"`
}

type Parameters struct {
	Contract         string            `json:"contract"`
	Provider         string            `json:"provider"`
	PipelineMode     string            `json:"pipelineMode"`
	Queries          map[string]string `json:"queries"`
	Targets          []Target          `json:"targets,omitempty"`
	EnrichmentPolicy string            `json:"enrichmentPolicy,omitempty"`
	RecoveryVersion  string            `json:"recoveryVersion,omitempty"`
}

func JobType(provider string) string { return "NEWS_" + provider + "_COLLECT" }
func IsJob(jobType string) bool      { return jobType == JobType("RSS") || jobType == JobType("GDELT") }

// Build uses the scheduled instant, not wall-clock time, so delayed ticks recover the intended days.
func Build(req Request, at time.Time) (domain.CreateJobRequest, error) {
	var empty domain.CreateJobRequest
	var selectionErr error
	req, selectionErr = prepareTargets(req)
	if selectionErr != nil {
		return empty, selectionErr
	}
	if req.Provider != "RSS" && req.Provider != "GDELT" {
		return empty, errors.New("provider must be RSS or GDELT")
	}
	if req.LookbackDays != 0 {
		if req.LookbackDays < 1 || req.LookbackDays > 7 || req.StartDate != "" || req.EndDate != "" {
			return empty, errors.New("lookbackDays must be 1..7 without fixed dates")
		}
		midnight := time.Date(at.UTC().Year(), at.UTC().Month(), at.UTC().Day(), 0, 0, 0, 0, time.UTC)
		req.StartDate = midnight.AddDate(0, 0, -req.LookbackDays).Format(time.DateOnly)
		req.EndDate = midnight.AddDate(0, 0, -1).Format(time.DateOnly)
	}
	start, e1 := time.Parse(time.DateOnly, req.StartDate)
	end, e2 := time.Parse(time.DateOnly, req.EndDate)
	if e1 != nil || e2 != nil || start.After(end) || end.Sub(start) >= 7*24*time.Hour || start.Before(time.Date(2015, 2, 19, 0, 0, 0, 0, time.UTC)) || !end.Add(24*time.Hour).Before(at.Add(time.Nanosecond)) {
		return empty, errors.New("use 1..7 completed UTC days from 2015-02-19")
	}
	params := Parameters{Contract: Version, Provider: req.Provider, PipelineMode: "COLLECT_ONLY", Queries: map[string]string{}}
	if req.DurableRecovery {
		params.RecoveryVersion = "news-coordinated-v1"
	}
	if len(req.Targets) > 0 {
		params.Contract = TargetVersion
		params.Targets = req.Targets
		params.EnrichmentPolicy = EnrichmentPolicy
	}
	if req.Provider == "RSS" {
		if len(req.Queries) < 1 || len(req.Queries) > 10 {
			return empty, errors.New("RSS requires 1..10 queries")
		}
		for _, q := range req.Queries {
			q = strings.TrimSpace(q)
			if len(q) < 2 || len(q) > 300 || strings.ContainsAny(q, "\r\n\x00") || strings.Contains(strings.ToLower(q), "after:") || strings.Contains(strings.ToLower(q), "before:") {
				return empty, errors.New("invalid RSS query; date filters are generated by the collector")
			}
			sum := sha256.Sum256([]byte(q))
			key := hex.EncodeToString(sum[:8])
			if _, exists := params.Queries[key]; exists {
				return empty, errors.New("duplicate RSS query")
			}
			params.Queries[key] = q
		}
	} else if len(req.Queries) != 0 {
		return empty, errors.New("GDELT archive collection does not accept keyword filters")
	}
	keys := []string{}
	for day := start; !day.After(end); day = day.AddDate(0, 0, 1) {
		if req.Provider == "RSS" {
			// Preserve request order for deterministic job plans.
			for _, q := range req.Queries {
				sum := sha256.Sum256([]byte(strings.TrimSpace(q)))
				keys = append(keys, "RSS:"+hex.EncodeToString(sum[:8])+":"+day.Format(time.DateOnly))
			}
		} else {
			for slot := 0; slot < 96; slot++ {
				keys = append(keys, "GKG:"+day.Add(time.Duration(slot)*15*time.Minute).Format("20060102150405"))
			}
		}
	}
	raw, err := json.Marshal(params)
	if err != nil {
		return empty, err
	}
	return domain.CreateJobRequest{JobType: JobType(req.Provider), Source: "NEWS", Parameters: raw, ItemKeys: keys}, nil
}

func Validate(jobType, source string, keys []string, raw json.RawMessage) error {
	var p Parameters
	if json.Unmarshal(raw, &p) != nil || (p.Contract != Version && p.Contract != TargetVersion) || p.PipelineMode != "COLLECT_ONLY" || source != "NEWS" || jobType != JobType(p.Provider) || (p.Provider != "RSS" && p.Provider != "GDELT") || len(keys) < 1 || len(keys) > 672 {
		return errors.New("invalid news collection contract")
	}
	if (p.Contract == TargetVersion) != (len(p.Targets) > 0) {
		return errors.New("news target contract mismatch")
	}
	if p.EnrichmentPolicy != "" && (p.EnrichmentPolicy != EnrichmentPolicy || p.Contract != TargetVersion) {
		return errors.New("invalid news enrichment policy")
	}
	if len(p.Targets) > 0 {
		r := Request{Provider: p.Provider, Targets: append([]Target(nil), p.Targets...)}
		for _, target := range p.Targets {
			r.AssetIDs = append(r.AssetIDs, target.AssetID)
		}
		resolved, err := prepareTargets(r)
		if err != nil {
			return err
		}
		if p.Provider == "RSS" {
			if len(p.Queries) != len(p.Targets) {
				return errors.New("news selected queries mismatch")
			}
			for i, target := range p.Targets {
				if p.Queries[target.QueryKey] != resolved.Queries[i] || target.QueryKey != resolved.Targets[i].QueryKey {
					return errors.New("news target query mismatch")
				}
			}
		}
	}
	if p.Provider == "RSS" && (len(p.Queries) < 1 || len(p.Queries) > 10) {
		return errors.New("invalid RSS queries")
	}
	for _, key := range keys {
		if p.Provider == "RSS" {
			parts := strings.Split(key, ":")
			if len(parts) != 3 || parts[0] != "RSS" {
				return errors.New("invalid RSS item")
			}
			q, ok := p.Queries[parts[1]]
			if !ok {
				return errors.New("unknown RSS query")
			}
			plan, err := Build(Request{Provider: "RSS", Queries: []string{q}, StartDate: parts[2], EndDate: parts[2]}, time.Now().UTC())
			if err != nil || plan.ItemKeys[0] != key {
				return fmt.Errorf("invalid RSS unit: %s", key)
			}
		} else {
			if !strings.HasPrefix(key, "GKG:") {
				return errors.New("invalid GKG item")
			}
			t, err := time.Parse("20060102150405", strings.TrimPrefix(key, "GKG:"))
			if err != nil || t.Minute()%15 != 0 || t.Second() != 0 || t.Before(time.Date(2015, 2, 19, 0, 0, 0, 0, time.UTC)) || t.After(time.Now().UTC().Add(-30*time.Minute)) {
				return errors.New("invalid GKG timestamp")
			}
		}
	}
	return nil
}
