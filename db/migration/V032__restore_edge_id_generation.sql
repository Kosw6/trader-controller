-- 복원된 레거시 DB의 edge.id는 bigint NOT NULL이지만 기본값/identity가 없을 수 있다.
-- JPA IDENTITY 계약과 맞추되, 이미 설정된 생성기/시퀀스는 초기화하지 않는다.
DO $$
DECLARE
    id_sequence text;
    largest_id bigint;
    deleted_id bigint;
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'edge' AND column_name = 'id'
          AND is_identity = 'NO' AND column_default IS NULL
    ) THEN
        -- 새 INSERT와 최대값 계산이 경합하지 않도록 동일 트랜잭션에서 잠근다.
        LOCK TABLE public.edge IN ACCESS EXCLUSIVE MODE;
        ALTER TABLE public.edge ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
        SELECT max(id) INTO largest_id FROM public.edge;
        -- 삭제된 검색 원본 ID도 재사용하면 안 된다. tombstone을 번호 상한에 포함한다.
        IF to_regclass('public.search_source_state') IS NOT NULL THEN
            SELECT max(source_id) INTO deleted_id FROM public.search_source_state
            WHERE source_type = 'EDGE';
        END IF;
        largest_id := greatest(coalesce(largest_id, 0), coalesce(deleted_id, 0));
        id_sequence := pg_get_serial_sequence('public.edge', 'id');
        PERFORM setval(id_sequence::regclass, largest_id + 1, false);
    END IF;
END $$;
