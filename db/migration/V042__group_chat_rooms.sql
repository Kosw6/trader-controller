-- Additive group chat only. No price/backfill/financial tables are touched.
SET lock_timeout = '3s';
CREATE TABLE group_chat_room (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL REFERENCES team(id) ON DELETE CASCADE,
    name varchar(60) NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 60),
    common_room boolean NOT NULL DEFAULT false,
    created_by bigint REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL
);
CREATE UNIQUE INDEX group_chat_one_common ON group_chat_room(team_id) WHERE common_room;
CREATE UNIQUE INDEX group_chat_room_name ON group_chat_room(team_id, lower(name));
CREATE TABLE group_chat_message (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id bigint NOT NULL REFERENCES group_chat_room(id) ON DELETE CASCADE,
    sender_id bigint REFERENCES users(id) ON DELETE SET NULL,
    nickname varchar(255) NOT NULL,
    content varchar(2000) NOT NULL CHECK (length(btrim(content)) BETWEEN 1 AND 2000),
    client_message_id varchar(36) NOT NULL,
    created_at timestamptz NOT NULL,
    CONSTRAINT group_chat_message_retry UNIQUE (room_id, sender_id, client_message_id)
);
CREATE INDEX group_chat_message_history ON group_chat_message(room_id, id DESC);
RESET lock_timeout;
